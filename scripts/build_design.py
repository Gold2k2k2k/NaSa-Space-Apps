"""Synchronize CSS custom properties with the committed design tokens."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def flatten(value, prefix=""):
    if isinstance(value, dict):
        for key, item in value.items():
            yield from flatten(item, f"{prefix}-{key}" if prefix else key)
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from flatten(item, f"{prefix}-{index}")
    else:
        yield prefix, value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    tokens = json.loads((ROOT / "design-tokens.json").read_text(encoding="utf-8"))
    properties = dict(flatten({key: value for key, value in tokens.items() if key not in ("name", "version")}))
    css = "/* Generated by scripts/build_design.py from design-tokens.json. */\n:root {\n"
    css += "".join(f"  --{key}: {value};\n" for key, value in properties.items()) + "}\n"
    target = ROOT / "app" / "web" / "static" / "tokens.css"
    template = (ROOT / "design-preview.template.html").read_text(encoding="utf-8")
    preview = template.replace("<!--TOKEN_CSS-->", css).replace("<!--TOKEN_JSON-->", json.dumps(tokens, ensure_ascii=False).replace("</", "<\\/"))
    targets = {target: css, ROOT / "design-preview.html": preview}
    if arguments.check:
        for path, expected in targets.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                print(f"Stale {path.name}; run python scripts/build_design.py")
                return 1
    else:
        for path, contents in targets.items():
            path.write_text(contents, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
